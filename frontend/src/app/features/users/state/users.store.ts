import { computed, inject, Injectable, signal } from '@angular/core';
import { NotificationService } from '../../../core/services/notification.service';
import { StaffApiService } from '../../../core/services/staff-api.service';
import { UsersApiService } from '../data-access/users-api.service';
import {
  AutoGeneratedEmployeeCredential,
  UserAccount,
  UsersQuery
} from '../data-access/models/user-account.model';

@Injectable({ providedIn: 'root' })
export class UsersStore {
  private readonly notificationService = inject(NotificationService);
  private readonly usersApiService = inject(UsersApiService);
  private readonly staffApiService = inject(StaffApiService);

  private readonly usersState = signal<UserAccount[]>([]);
  private readonly loadingState = signal(false);
  private readonly selectedUserState = signal<UserAccount | null>(null);
  private readonly selectedUserLoadingState = signal(false);
  private readonly queryState = signal<UsersQuery>({ page: 0, size: 20 });
  private readonly totalElementsState = signal(0);
  private readonly generatedCredentialState = signal<AutoGeneratedEmployeeCredential | null>(null);

  readonly users = this.usersState.asReadonly();
  readonly loading = this.loadingState.asReadonly();
  readonly selectedUser = this.selectedUserState.asReadonly();
  readonly selectedUserLoading = this.selectedUserLoadingState.asReadonly();
  readonly generatedCredential = this.generatedCredentialState.asReadonly();
  readonly employeeCount = this.totalElementsState.asReadonly();

  readonly activeUsers = computed(() => this.usersState().filter((user) => user.active).length);

  readonly totalOrdersToday = computed(() =>
    this.usersState().reduce((total, user) => total + (user.ordersToday || 0), 0)
  );
  readonly totalOrdersThisMonth = computed(() =>
    this.usersState().reduce((total, user) => total + (user.ordersThisMonth || 0), 0)
  );

  loadUsers(partialQuery: Partial<UsersQuery> = {}): void {
    const query = { ...this.queryState(), ...partialQuery };
    this.queryState.set(query);
    this.loadingState.set(true);

    this.usersApiService.list(query).subscribe({
      next: (response) => {
        if (!response || !response.content) {
          this.usersState.set([]);
          this.totalElementsState.set(0);
          this.loadingState.set(false);
          return;
        }

        // Map backend response to frontend model
        const mappedUsers: UserAccount[] = response.content.map((u: any) => this.mapUserFromApi(u));

        this.usersState.set(mappedUsers);
        this.totalElementsState.set(response.totalElements || 0);

        // Update selected user if none or if current selection is not in new list
        const currentSelectedId = this.selectedUserState()?.id;
        if (!currentSelectedId || !mappedUsers.some((u) => u.id === currentSelectedId)) {
          const nextSelectedUser = mappedUsers[0] ?? null;
          this.selectedUserState.set(nextSelectedUser);

          if (nextSelectedUser) {
            this.loadUserDetail(nextSelectedUser.id);
          }
        } else {
          const existingSelection = this.selectedUserState();
          const refreshedSelectedUser = mappedUsers.find((u) => u.id === currentSelectedId) ?? null;

          this.selectedUserState.set(
            existingSelection && refreshedSelectedUser
              ? { ...existingSelection, ...refreshedSelectedUser }
              : refreshedSelectedUser
          );

          this.loadUserDetail(currentSelectedId);
        }

        this.loadingState.set(false);
      },
      error: (err) => {
        this.notificationService.error('Không thể tải danh sách nhân viên: ' + (err.error?.message || 'Lỗi kết nối'));
        this.loadingState.set(false);
      }
    });
  }

  autoGenerateEmployeeAccount(fullName: string): void {
    this.loadingState.set(true);

    this.staffApiService.createStaff({
      fullName: fullName.trim()
    }).subscribe({
      next: (staff) => {
        const credential: AutoGeneratedEmployeeCredential = {
          employeeId: String(staff.id),
          fullName: staff.fullName,
          username: staff.username,
          email: staff.email,
          temporaryPassword: staff.temporaryPassword || '',
          createdAt: new Date().toISOString()
        };

        this.generatedCredentialState.set(credential);
        this.notificationService.success(`Đã tạo tài khoản cho ${staff.fullName}`);
        this.loadUsers({ page: 0 }); // Refresh list
      },
      error: (err) => {
        this.notificationService.error('Không thể tạo tài khoản: ' + (err.error?.message || 'Lỗi hệ thống'));
        this.loadingState.set(false);
      }
    });
  }

  clearGeneratedCredential(): void {
    this.generatedCredentialState.set(null);
  }

  selectUser(user: UserAccount | null): void {
    this.selectedUserState.set(user);

    if (user) {
      this.loadUserDetail(user.id);
    } else {
      this.selectedUserLoadingState.set(false);
    }
  }

  private loadUserDetail(userId: string): void {
    this.selectedUserLoadingState.set(true);

    this.usersApiService.getById(userId).subscribe({
      next: (response) => {
        if (this.selectedUserState()?.id !== userId) {
          return;
        }

        const detailedUser = this.mapUserFromApi(response);

        this.selectedUserState.set({
          ...(this.selectedUserState() ?? {}),
          ...detailedUser
        } as UserAccount);

        this.usersState.update((users) =>
          users.map((user) => (user.id === userId ? { ...user, ...detailedUser } : user))
        );

        this.selectedUserLoadingState.set(false);
      },
      error: (err) => {
        if (this.selectedUserState()?.id !== userId) {
          return;
        }

        this.notificationService.error(
          'Không thể tải chi tiết nhân viên: ' + (err.error?.message || 'Lỗi kết nối')
        );
        this.selectedUserLoadingState.set(false);
      }
    });
  }

  private mapUserFromApi(u: any): UserAccount {
    const forceChangePassword = u.forceChangePassword ?? false;

    return {
      id: String(u.id),
      fullName: u.fullName,
      email: u.email,
      username: u.username,
      phone: u.phone ?? null,
      role: (u.role || 'STAFF') as UserAccount['role'],
      active: u.isActive ?? u.active ?? true,
      forceChangePassword,
      createdAt: u.createdAt,
      lastLogin: u.lastLogin ?? null,
      ordersToday: u.ordersToday || 0,
      ordersThisMonth: u.ordersThisMonth || 0,
      temporaryPassword: forceChangePassword ? u.temporaryPassword : null,
      handledOrders: u.handledOrders ?? []
    };
  }
}
