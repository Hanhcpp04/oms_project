export type UserRole = 'OWNER' | 'ADMIN' | 'STAFF' | 'OPERATOR' | 'VIEWER';

export type EmployeeOrderStatus = 'NEW' | 'PROCESSING' | 'SHIPPED' | 'COMPLETED' | 'CANCELLED';

export interface EmployeeHandledOrder {
  orderCode: string;
  customerName: string;
  status: EmployeeOrderStatus;
  handledAt: string;
}

export interface UserAccount {
  id: string;
  fullName: string;
  email: string;
  username: string;
  phone?: string | null;
  role: UserRole;
  active: boolean;
  forceChangePassword?: boolean;
  createdAt?: string;
  lastLogin?: string | null;
  ordersToday?: number;
  ordersThisMonth?: number;
  temporaryPassword?: string;
  handledOrders?: EmployeeHandledOrder[];
}

export interface AutoGeneratedEmployeeCredential {
  employeeId: string;
  fullName: string;
  username: string;
  email: string;
  temporaryPassword: string;
  createdAt: string;
}

export interface UsersQuery {
  page: number;
  size: number;
  search?: string;
}
